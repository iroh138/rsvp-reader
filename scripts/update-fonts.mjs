// Regenerates vendor/fonts/ (woff2 files + fonts.css) from Fontsource npm tarballs, so the app loads no fonts
// from third-party servers (CONTROLS.md PRV-04). Keeps the same families, weights and scripts the app used to
// request from Google Fonts: Literata (optical size axis), IBM Plex Sans 400/500/600, IBM Plex Mono 400/500.
//
// Usage (owner, when updating fonts):
//   mkdir /tmp/f && cd /tmp/f && npm pack @fontsource-variable/literata@5.3.0 @fontsource/ibm-plex-sans@5.3.0 @fontsource/ibm-plex-mono@5.3.0
//   for f in *.tgz; do mkdir -p "${f%.tgz}" && tar xzf "$f" -C "${f%.tgz}"; done
//   node scripts/update-fonts.mjs /tmp/f
// Then update vendor/SHA256SUMS (sha256sum of every vendored file) and review the diff.
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/update-fonts.mjs <folder with extracted Fontsource tarballs>'); process.exit(1); }
const root = fileURLToPath(new URL('..', import.meta.url));
const out = join(root, 'vendor/fonts');

// [package folder, css files, family name to use in the app]
const SETS = [
  ['fontsource-variable-literata-5.3.0', ['opsz.css'], 'Literata'],
  ['fontsource-ibm-plex-sans-5.3.0', ['400.css', '500.css', '600.css'], 'IBM Plex Sans'],
  ['fontsource-ibm-plex-mono-5.3.0', ['400.css', '500.css'], 'IBM Plex Mono'],
];

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
let css = '/* Generated by scripts/update-fonts.mjs from Fontsource packages (SIL Open Font License 1.1). Do not edit. */\n';
const files = new Set();
for (const [pkg, sheets, family] of SETS) {
  for (const sheet of sheets) {
    const text = await readFile(join(src, pkg, 'package', sheet), 'utf8');
    for (const block of text.match(/@font-face\s*{[^}]*}/g) || []) {
      const woff2 = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/);
      if (!woff2) throw new Error(`no woff2 in a block of ${pkg}/${sheet}`);
      files.add([pkg, woff2[1]]);
      const fmt = /woff2-variations/.test(block) ? 'woff2-variations' : 'woff2';
      css += block
        .replace(/font-family:\s*'[^']+'/, `font-family: '${family}'`)
        .replace(/src:[^;]+;/, `src: url(./${woff2[1]}) format('${fmt}');`) + '\n';
    }
  }
}
for (const [pkg, f] of files) await copyFile(join(src, pkg, 'package/files', f), join(out, f));
await copyFile(join(src, SETS[0][0], 'package/LICENSE'), join(out, 'OFL-Literata.txt'));
await copyFile(join(src, SETS[1][0], 'package/LICENSE'), join(out, 'OFL-IBM-Plex.txt'));
await writeFile(join(out, 'fonts.css'), css);
console.log(`vendor/fonts: ${files.size} woff2 files, ${(css.match(/@font-face/g) || []).length} @font-face rules`);
